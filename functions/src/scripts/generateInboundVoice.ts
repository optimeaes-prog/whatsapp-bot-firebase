function getArg(name: string): string | undefined {
  const prefix = `--${name}=`;
  const hit = process.argv.find((a) => a.startsWith(prefix));
  return hit ? hit.slice(prefix.length).trim() : undefined;
}

async function main(): Promise<void> {
  const apiKey = (getArg("key") || process.env.ELEVENLABS_KEY || process.env["11LABS_KEY"] || "").trim();
  if (!apiKey) {
    throw new Error('Missing ElevenLabs API key. Provide "--key=<key>" or set ELEVENLABS_KEY.');
  }

  // Optional filter so locuciones can be re-recorded one at a time after a wording tweak.
  // Comma-separated, matched as substrings. Worth using: ElevenLabs pins no seed, so
  // regenerating a locución whose text did NOT change still yields a different take of it.
  const only = (getArg("only") || "")
    .toLowerCase()
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);

  // Without --only, hand-made locuciones are left alone. Naming one explicitly overrides
  // that, so the protection can never become a wall — it just stops accidents.
  const targets = only.length
    ? LOCUCIONES.filter((l) => only.some((o) => l.file.toLowerCase().includes(o)))
    : LOCUCIONES.filter((l) => !l.handMade);

  if (!targets.length) {
    const names = LOCUCIONES.map((l) => `${l.file}${l.handMade ? " (hand-made)" : ""}`).join(", ");
    throw new Error(
      only.length ? `--only=${only.join(",")} matched none of: ${names}` : `Nothing to generate. Known locuciones: ${names}`
    );
  }

  const skipped = LOCUCIONES.filter((l) => !targets.includes(l));
  if (skipped.length) {
    console.log(`Skipping ${skipped.length} locución(es): ${skipped.map((l) => l.file).join(", ")}`);
  }

  // Compiled location: functions/lib/scripts/generateInboundVoice.js → repo root is three levels up.
  const repoRoot = path.resolve(__dirname, "..", "..", "..");
  const outDir = path.join(repoRoot, "public", "voice");
  fs.mkdirSync(outDir, { recursive: true });

  for (const loc of targets) {
    if (loc.handMade) {
      console.warn(`! ${loc.file} is hand-made — regenerating REPLACES the approved take.`);
    }
    process.stdout.write(`Generating ${loc.file} (voiceId ${loc.voiceId}) … `);
    const mp3 = await generateSpeechMp3({ apiKey, voiceId: loc.voiceId, text: loc.text });
    const dest = path.join(outDir, loc.file);
    fs.writeFileSync(dest, mp3);
    console.log(`done — ${mp3.length} bytes → ${dest}`);
  }

  console.log(`\n${targets.length} locución(es) generated with the approved ElevenLabs voices.`);
  console.log("Next: build the frontend and deploy hosting + the voice functions.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
