import fs from "node:fs";
import path from "node:path";

import { generateSpeechMp3 } from "../services/elevenLabsClient";

/**
 * One-off script: (re)generate the INBOUND voice locuciones with the approved ElevenLabs
 * voices, so every leg of the inbound phone call sounds like the same person.
 *
 * The call is bilingual: the caller hears a short language menu, waits for Spanish or
 * presses 1 for English, and the rest of the call plays in the chosen language. Each
 * language has its own approved voice — Spanish lines are never spoken by the English
 * voice and vice versa, which is why the locución list carries a voiceId per entry.
 *
 * VOICE_ID_ES MUST match OUTBOUND_ELEVENLABS_VOICE_ID_DEFAULT in src/index.ts.
 *
 * IMPORTANT — most of these locuciones are `handMade` (see below) and a plain run SKIPS
 * them. Only the entries without that flag are regenerated by default. This is deliberate:
 * the approved recordings were tuned by ear in the ElevenLabs web UI with settings this
 * script does not reproduce, and re-rendering them would silently swap the audio callers
 * hear for a different take of the same words.
 *
 * Files are written to <repoRoot>/public/voice/ ; Vite copies public/ into dist/ on the
 * frontend build, and Firebase Hosting serves them under /voice/** with `Cache-Control: no-store`,
 * so overwriting in place is safe (no cache busting / filename versioning needed).
 *
 * Run:
 *   cd functions
 *   ELEVENLABS_KEY=<your-key> npm run generate:inbound-voice
 *   # or: npm run generate:inbound-voice -- --key=<your-key>
 *
 * Regenerating specific locuciones after a wording tweak (comma-separated, substring match):
 *   npm run generate:inbound-voice -- --key=<your-key> --only=message_part_2_optin_en
 */

// Approved ElevenLabs voices.
// Spanish — "Dani". Keep in sync with OUTBOUND_ELEVENLABS_VOICE_ID_DEFAULT in src/index.ts.
const VOICE_ID_ES = "7QQzpAyzlKTVrRzQJmTE";
// English (British) — "Daniel". Used only for the English branch of the inbound call.
const VOICE_ID_EN = "u8GDilEiJPUbRk87Lcqs";

type Locucion = {
  file: string;
  voiceId: string;
  /**
   * For generated entries: the exact text sent to ElevenLabs.
   * For `handMade` entries: a reference copy of the script, NOT the source of the audio —
   * the committed .mp3 is authoritative and may differ in wording or delivery.
   */
  text: string;
  /**
   * Recorded by hand in the ElevenLabs web UI and committed as-is. Skipped by a plain run.
   * Naming one explicitly with --only still regenerates it, which replaces the approved
   * take — only do that deliberately.
   */
  handMade?: true;
};

